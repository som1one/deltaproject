async def main() -> None:
    init_db(_normalize(settings.database_url))
    factory = get_session_factory()

    added = 0
    skipped = 0
    async with factory() as db:
        # Берём максимальный sort_order, чтобы новые шли в конец списка.
        max_order_result = await db.execute(
            select(WorkerMessageScript.sort_order).order_by(WorkerMessageScript.sort_order.desc()).limit(1),
        )
        max_order = max_order_result.scalar() or 0
        cursor = max_order

        for title, body, category, keywords in SCRIPTS:
            existing = await db.execute(
                select(WorkerMessageScript).where(WorkerMessageScript.title == title),
            )
            if existing.scalar_one_or_none() is not None:
                skipped += 1
                continue
            cursor += 10
            db.add(
                WorkerMessageScript(
                    id=uuid4(),
                    title=title,
                    body=body,
                    category=category,
                    keywords=keywords,
                    sort_order=cursor,
                ),
            )
            added += 1

        await db.commit()

    print(f"Worker scripts: added={added}, skipped (already present)={skipped}")
    await dispose_db()


if __name__ == "__main__":
    asyncio.run(main())
